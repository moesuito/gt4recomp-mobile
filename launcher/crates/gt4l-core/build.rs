//! Build script (TASK-102): the launcher's own messages are translated in the same locale files as the page
//! (`launcher/crates/gt4l-tauri/ui/locales/<tag>.json`), under keys that start with `rust.`. This script reads
//! `index.json` (the list of languages, the first one is the fallback) and every listed locale file, and writes
//! `$OUT_DIR/locales.rs` with:
//! - `FALLBACK_TAG`: the first tag of `index.json` (en-US);
//! - `LANGUAGE_TAGS`: (tag, name) of every listed language, in `index.json` order;
//! - `TEXTS`: (tag, message id, text) for every `rust.<id>` key of every language.
//! A new language is a new locale file plus an entry in `index.json`; nothing here names a language.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const RUST_PREFIX: &str = "rust.";

fn read_json(path: &Path) -> serde_json::Value {
    let text = std::fs::read_to_string(path).unwrap_or_else(|error| panic!("{} is not readable: {error}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|error| panic!("{} is not valid JSON: {error}", path.display()))
}

fn quoted(text: &str) -> String {
    format!("{text:?}")
}

/// The release label of this build (TASK-109): `GT4_RELEASE_LABEL=rc5` makes the launcher version `1.3.0-rc5`, and
/// `GT4_RELEASE_LABEL=android-test3` makes it `1.3.0-android-test3` (the Android test builds, TASK-180). Empty or
/// missing = a stable build. Anything but `rc<N>` or `android-test<N>` (an Android test build may carry one more
/// `-suffix`, the private builds' name, e.g. `android-test4-armsx2gs-private`) stops the build.
fn release_label() {
    println!("cargo:rerun-if-env-changed=GT4_RELEASE_LABEL");
    let label = std::env::var("GT4_RELEASE_LABEL").unwrap_or_default();
    let label = label.trim();
    if !label.is_empty() {
        let valid = |prefix: &str, allow_suffix: bool| {
            let rest = label.strip_prefix(prefix).unwrap_or("");
            let (digits, suffix) = match rest.split_once('-') {
                Some((digits, suffix)) => (digits, Some(suffix)),
                None => (rest, None),
            };
            let numbered = !digits.is_empty() && digits.bytes().all(|byte| byte.is_ascii_digit()) && !digits.starts_with('0');
            let suffix_ok = match suffix {
                None => true,
                Some(text) => {
                    allow_suffix
                        && !text.is_empty()
                        && text.bytes().all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
                }
            };
            numbered && suffix_ok
        };
        let valid = valid("rc", false) || valid("android-test", true);
        assert!(
            valid,
            "GT4_RELEASE_LABEL must be empty, rc<N> or android-test<N> (N from 1, no leading zero; android-test may carry -suffix), got '{label}'"
        );
    }
    let cargo = std::env::var("CARGO_PKG_VERSION").expect("CARGO_PKG_VERSION");
    let full = if label.is_empty() { cargo } else { format!("{cargo}-{label}") };
    println!("cargo:rustc-env=GT4_LAUNCHER_VERSION={full}");
    println!("cargo:rustc-env=GT4_RELEASE_LABEL={label}");
}

fn main() {
    release_label();
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let locales = manifest.join("../gt4l-tauri/ui/locales");
    println!("cargo:rerun-if-changed={}", locales.display());

    let index_path = locales.join("index.json");
    println!("cargo:rerun-if-changed={}", index_path.display());
    let index = read_json(&index_path);
    let languages: Vec<(String, String)> = index
        .as_array()
        .expect("index.json is a list of {tag, name}")
        .iter()
        .map(|entry| {
            let tag = entry["tag"].as_str().expect("every index.json entry has a tag").to_string();
            let name = entry["name"].as_str().expect("every index.json entry has a name").to_string();
            (tag, name)
        })
        .collect();
    assert!(!languages.is_empty(), "index.json lists no language");

    let mut source = String::from("// Generated by build.rs from ui/locales (TASK-102). Do not edit.\n");
    let _ = writeln!(source, "/// The fallback language: the first entry of index.json.");
    let _ = writeln!(source, "pub const FALLBACK_TAG: &str = {};", quoted(&languages[0].0));
    let _ = writeln!(source, "/// Every language of index.json: (tag, name), in its order.");
    let _ = writeln!(source, "pub const LANGUAGE_TAGS: &[(&str, &str)] = &[");
    for (tag, name) in &languages {
        let _ = writeln!(source, "    ({}, {}),", quoted(tag), quoted(name));
    }
    let _ = writeln!(source, "];");
    let _ = writeln!(source, "/// Every launcher message text: (language tag, message id, text).");
    let _ = writeln!(source, "pub const TEXTS: &[(&str, &str, &str)] = &[");
    for (tag, _) in &languages {
        let path = locales.join(format!("{tag}.json"));
        println!("cargo:rerun-if-changed={}", path.display());
        let locale = read_json(&path);
        let object = locale.as_object().unwrap_or_else(|| panic!("{} is a JSON object", path.display()));
        let mut ids: Vec<(&String, &serde_json::Value)> = object.iter().filter(|(key, _)| key.starts_with(RUST_PREFIX)).collect();
        ids.sort_by(|a, b| a.0.cmp(b.0));
        for (key, value) in ids {
            let text = value.as_str().unwrap_or_else(|| panic!("{key} in {tag} is a string"));
            let id = &key[RUST_PREFIX.len()..];
            let _ = writeln!(source, "    ({}, {}, {}),", quoted(tag), quoted(id), quoted(text));
        }
    }
    let _ = writeln!(source, "];");

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out.join("locales.rs"), source).expect("write locales.rs");
}
